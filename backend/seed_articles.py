def seed():
    db = SessionLocal()
    try:
        existing = db.query(Article).count()
        if existing > 0:
            print(f"数据库中已有 {existing} 篇文章，跳过初始化")
            print("如需重新初始化，请先清空 articles 表")
            return

        for data in ARTICLES:
            article = Article(
                content_type=data["content_type"],
                title=data["title"],
                summary=data["summary"],
                content=data["content"],
                tags=data["tags"],
                author=data["author"],
                is_published=data["is_published"],
                is_featured=data["is_featured"],
                view_count=data["view_count"],
                created_at=datetime.utcnow(),
                updated_at=datetime.utcnow(),
            )
            db.add(article)

        db.commit()
        print(f"✅ 成功插入 {len(ARTICLES)} 篇科普文章")
        for a in ARTICLES:
            print(f"  - {a['title']}")
    except Exception as e:
        db.rollback()
        print(f"❌ 插入失败: {e}")
        raise
    finally:
        db.close()

if __name__ == "__main__":
    seed()
